/* ==========================================================================
   100% Juice — rename tool (docs/rename.html)
   Plain vanilla JS, no build step.

   Private contact sheet: shows every sticker from products-data.js with its
   current (guessed) name, lets you type the real name + description, then
   generates a corrected js/products-data.js you can copy back into the file.

   Loaded after products-data.js (uses the global `PRODUCTS`). Self-contained —
   it does NOT depend on app.js, so it defines its own tiny escapeHtml helper.
   ========================================================================== */

function escapeHtml(str) {
  return String(str == null ? "" : str)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

document.addEventListener("DOMContentLoaded", () => {
  const grid = document.getElementById("rename-grid");
  const generateBtn = document.getElementById("generate-btn");
  const copyBtn = document.getElementById("copy-btn");
  const out = document.getElementById("code-out");
  const statusEl = document.getElementById("copy-status");

  if (!grid) return;
  if (typeof PRODUCTS === "undefined") {
    grid.innerHTML = '<p class="cart-empty">products-data.js failed to load.</p>';
    return;
  }

  // Editable working copy of every product. Kept keyed by array index so two
  // stickers that share a displayName never overwrite each other.
  const working = PRODUCTS.map((p) => Object.assign({}, p));

  function buildCard(product, index) {
    const card = document.createElement("article");
    card.className = "rename-card";
    card.innerHTML = `
      <img src="${escapeHtml(product.img)}" alt="${escapeHtml(product.displayName)}" loading="lazy">
      <div class="current">
        Current name: <strong>${escapeHtml(product.displayName)}</strong><br>
        Current description: ${escapeHtml(product.description)}
      </div>
      <div class="rename-field">
        <label for="name-${index}">Name</label>
        <input id="name-${index}" type="text" value="${escapeHtml(product.displayName)}" data-field="displayName">
      </div>
      <div class="rename-field">
        <label for="desc-${index}">Description</label>
        <textarea id="desc-${index}" rows="2" data-field="description">${escapeHtml(product.description)}</textarea>
      </div>
      <div class="uuid">${escapeHtml(product.uuid)} &middot; ${escapeHtml(product.size)} &middot; ${escapeHtml(product.price)}</div>
    `;
    card.querySelectorAll("[data-field]").forEach((el) => {
      el.addEventListener("input", () => {
        working[index][el.dataset.field] = el.value;
      });
    });
    return card;
  }

  function render() {
    grid.innerHTML = "";
    working.forEach((p, i) => grid.appendChild(buildCard(p, i)));
  }

  // Build the full, corrected products-data.js as a string.
  function generateFile() {
    const header = [
      "// products-data.js",
      "// -----------------------------------------------------------------------------",
      "// Generated by docs/rename.html — paste this over the old js/products-data.js.",
      "// Names and descriptions are the real sticker names you typed into the tool.",
      "// The uuid is the artwork id (matches docs/img/products/<uuid>.png).",
      "// Prices are $0.00 for every sticker.",
      "// -----------------------------------------------------------------------------",
    ].join("\n");

    const entries = working.map((p) =>
      [
        "  {",
        `    "uuid": ${JSON.stringify(p.uuid)},`,
        `    "displayName": ${JSON.stringify(p.displayName)},`,
        `    "description": ${JSON.stringify(p.description)},`,
        `    "size": ${JSON.stringify(p.size)},`,
        `    "price": ${JSON.stringify(p.price)},`,
        `    "img": ${JSON.stringify(p.img)}`,
        "  }",
      ].join("\n")
    );

    return header + "\nconst PRODUCTS = [\n" + entries.join(",\n") + "\n];\n";
  }

  generateBtn.addEventListener("click", () => {
    const text = generateFile();
    out.value = text;
    out.focus();
    out.select();
    console.log("[rename] generated products-data.js:\n" + text);
    if (statusEl) statusEl.textContent = "Generated " + working.length + " entries. Hit Copy to grab the whole file.";
  });

  copyBtn.addEventListener("click", async () => {
    if (!out.value) out.value = generateFile();
    const text = out.value;
    let ok = false;
    try {
      if (navigator.clipboard && navigator.clipboard.writeText) {
        await navigator.clipboard.writeText(text);
        ok = true;
      }
    } catch (err) {
      ok = false; // fall through to the execCommand fallback
    }
    if (!ok) {
      out.focus();
      out.select();
      try {
        ok = document.execCommand("copy");
      } catch (err) {
        ok = false;
      }
    }
    if (statusEl) {
      statusEl.textContent = ok
        ? "Copied to clipboard."
        : "Auto-copy blocked — the text is selected, press Cmd/Ctrl+C.";
    }
  });

  render();
});
